/**
 * Get translated agent UI strings for a language code.
 * Falls back to English for unsupported languages.
 */
export function getAgentStrings(language: string): AgentStrings {
  // Try exact match, then base language (e.g., "zh-cn" -> "zh")
  return (
    STRINGS[language] ??
    STRINGS[language.split("-")[0]] ??
    EN
  );
}

/**
 * The writer's name for a workflow. The maps are keyed by WorkflowId so a
 * missing translation is a build error (H-4); callers hold a plain string id,
 * so this is where the narrowing happens — once, instead of an `as` at each of
 * the sixteen call sites.
 *
 * H-5: the fallback is the ENGLISH DICTIONARY entry, not the registry label.
 * Falling back to the registry made a missing translation render as perfectly
 * ordinary English, which is why 27 missing keys per language survived every
 * test that only asserted "it renders something".
 */
export function workflowLabel(strings: AgentStrings, id: string): string | undefined {
  const table = strings.workflows as Record<string, string | undefined>;
  const english = EN.workflows as Record<string, string | undefined>;
  return table[id] ?? english[id];
}

/** The writer's description of a workflow. Same fallback rule as the label. */
export function workflowDescription(strings: AgentStrings, id: string): string | undefined {
  const table = strings.workflowDescriptions as Record<string, string | undefined>;
  const english = EN.workflowDescriptions as Record<string, string | undefined>;
  return table[id] ?? english[id];
}
