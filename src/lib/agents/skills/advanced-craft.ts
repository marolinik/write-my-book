// ─── 1. Dialogue Mastery ─────────────────────────────────────

export const DIALOGUE_MASTERY = `
## Dialogue Mastery Guide

### The 4 Functions of Dialogue
Every line of dialogue must serve at least ONE of these:
1. **Advance the plot** — reveal information, make decisions, trigger action
2. **Reveal character** — voice, values, intelligence, emotional state
3. **Create tension** — disagreement, subtext, power dynamics
4. **Set atmosphere** — era, culture, social class, setting

### Subtext Techniques
- **Displacement**: Characters talk about something else when the real issue is too painful
  "Nice weather" (while their marriage collapses)
- **Deflection**: Answering a question with a question or a non-sequitur
  "Did you love her?" → "Have you eaten?"
- **Understatement**: Saying less than what's felt
  "It was... difficult" (after surviving a war)
- **Contradiction**: Actions contradict words
  "I'm fine" (while hands are shaking)

### Voice Differentiation Checklist
For each character, define:
- Vocabulary level (simple/educated/technical/slang)
- Sentence length tendency (clipped/average/verbose)
- Verbal tics ("you know", "frankly", "the thing is")
- Topics they default to when nervous
- What they NEVER say (topics they avoid)
- Cultural/regional markers (accent, idioms)
- How they address different people (formal/casual)

### Dialogue Formatting Rules
- New speaker = new paragraph (always)
- Action beats can replace dialogue tags: He slammed the door. "Get out."
- Interruptions: em dash at the cut-off point: "But I never—"
- Trailing off: ellipsis: "I thought maybe..."
- Internal dialogue in italics (optional): *This is wrong.*
`;

// ─── 2. Action Scene Choreography ────────────────────────────

export const ACTION_CHOREOGRAPHY = `
## Action Scene Choreography

### The SPACE Method
Before writing any action scene, establish:
- **S**pace: Where exactly are the characters? Map the room/terrain.
- **P**ositions: Where is each character relative to others?
- **A**rsenal: What weapons/tools/advantages does each side have?
- **C**onstraints: What limits movement? (walls, injuries, civilians, time)
- **E**xit: What's the escape route? What's the goal?

### Pacing Rules for Action
- Sentences get SHORTER as intensity increases
- One action per sentence during peak intensity
- Paragraph breaks = beats of time (each paragraph ≈ 1-3 seconds)
- Use white space (short paragraphs) for impact moments
- Sensory details ONLY from the POV character's awareness
- Pain and exhaustion accumulate — don't forget the body

### Common Action Writing Mistakes
- Characters who fight without tiring or getting hurt
- "Camera" suddenly becoming omniscient during fights
- Blow-by-blow choreography that reads like stage directions
- Action scenes with no emotional stakes
- Perfect aim, perfect timing, perfect plans that work
- Forgetting the environment (furniture, weather, footing)
- Post-fight scenes where injuries magically disappear

### Rhythm Pattern
Build-up (long sentences, tension rising) →
Explosion (short, sharp, one-beat sentences) →
Aftermath (medium sentences, assess damage, emotional landing)
`;

// ─── 3. Worldbuilding Depth Reference ────────────────────────

export const WORLDBUILDING_DEPTH = `
## Worldbuilding Depth Reference

### The Iceberg Principle
Show 10% of your worldbuilding. Know 100%.
The reader should sense depth beyond what's on the page.

### 7 Layers of Worldbuilding
1. **Geography & Climate**: Terrain, weather patterns, natural resources, how geography shapes culture
2. **History**: Wars, dynasties, migrations, founding myths, what people REMEMBER vs. what happened
3. **Social Structure**: Class system, mobility, who has power and why, gender roles, age hierarchies
4. **Economy**: What's valuable, trade routes, who's rich, who's poor, what do people DO for work
5. **Belief Systems**: Religion(s), superstitions, moral frameworks, creation myths, afterlife beliefs
6. **Language & Communication**: Dialect variations, formality registers, written vs. oral traditions, banned words
7. **Daily Life**: Food, clothing, housing, family structure, entertainment, hygiene, time-keeping

### Worldbuilding Integration Rules
- NEVER infodump — reveal through character interaction with the world
- Characters don't explain their own world to each other (they already know it)
- Use telling details: one specific cultural practice reveals more than a page of exposition
- Consistency > creativity: a simple world that's internally consistent beats a complex world with holes
- The world should CONSTRAIN your characters — their choices should be shaped by their environment

### Questions to Test Depth
- What do ordinary people eat for breakfast?
- How do people greet strangers vs. friends?
- What's the most common cause of death?
- What do children play at?
- What do people fear that isn't real?
`;

// ─── 4. Character Voice Sheet ────────────────────────────────

export const CHARACTER_VOICE_SHEET = `
## Character Voice Differentiation Sheet

### The Voice DNA Test
Can you tell who's speaking WITHOUT dialogue tags?
If not, voices aren't distinct enough.

### Voice Components (per character)
**Vocabulary Profile**
- Word length preference (monosyllabic vs. polysyllabic)
- Jargon domains (medical, military, academic, street)
- Forbidden words (what this character would NEVER say)
- Favorite expressions (pet phrases, catchphrases)

**Syntax Pattern**
- Average sentence length (count it!)
- Fragment usage (yes/no, frequency)
- Question frequency (some characters question everything)
- Compound vs. simple sentences
- Active vs. passive voice tendency

**Emotional Expression**
- Direct vs. indirect ("I'm angry" vs. "Don't touch me")
- Physical vs. verbal (punches wall vs. says something cutting)
- Humor style (sarcasm, self-deprecation, dark, none)
- Vulnerability threshold (what breaks through their walls)

**Speech Rhythm**
- Fast talker vs. measured speaker
- Interrupts vs. waits
- Monologuer vs. minimalist
- Formal vs. casual register shifts

### Dialogue Stress Test
Write the same message as each character:
"We need to leave now because there's danger."
- Soldier: "Move. Now."
- Professor: "I believe the situation has become untenable. We should consider—"
- Teenager: "Oh my god, we gotta go, like RIGHT now."
- Diplomat: "Perhaps it would be prudent to relocate at our earliest convenience."
`;

// ─── 5. Pacing & Tension Curve ───────────────────────────────

export const PACING_TENSION = `
## Pacing & Tension Curve Guide

### The Tension Equation
Tension = (What the reader FEARS might happen) × (How much they CARE) ÷ (How much they KNOW)

### Pacing Tools (Speed Control)
**ACCELERATE** (shorter chapters, faster prose):
- Short sentences. Fragments. Action.
- Minimal description — just movement and dialogue
- Time compression: "Three days later..."
- Cliffhanger chapter endings
- Remove transitions — cut between scenes

**DECELERATE** (longer chapters, contemplative prose):
- Extended sensory description
- Internal monologue and reflection
- Detailed conversation with subtext
- Flashback or memory
- Environmental description that mirrors emotion

### The Micro-Tension Checklist (per scene)
Even in "quiet" scenes, at least ONE of these should be present:
- [ ] Unanswered question from a previous scene
- [ ] Character hiding something from another character
- [ ] Disagreement (even subtle) between characters
- [ ] Ticking clock (even minor: dinner getting cold)
- [ ] Dramatic irony (reader knows something a character doesn't)
- [ ] Internal conflict (character wants two contradictory things)
- [ ] Environmental pressure (weather, noise, discomfort)
- [ ] Foreshadowing (ominous detail that pays off later)

### Genre-Specific Pacing Norms
- **Thriller**: 2,000-3,000 word chapters, cliffhanger every chapter, 40+ chapters
- **Literary**: 4,000-8,000 word chapters, contemplative, 15-25 chapters
- **Romance**: 3,000-5,000 word chapters, alternating POV, 25-35 chapters
- **Fantasy**: 4,000-6,000 word chapters, variable pace, 25-40 chapters
- **YA**: 2,000-4,000 word chapters, fast pace, 25-35 chapters
`;

// ─── 6. Query/Synopsis/Blurb Crafting ────────────────────────

export const QUERY_SYNOPSIS_BLURB = `
## Query Letter, Synopsis & Blurb Crafting

### Query Letter Formula (250-400 words)
**Paragraph 1 — Hook (2-3 sentences)**
[PROTAGONIST] is a [BRIEF DESCRIPTOR] who [SITUATION].
When [INCITING INCIDENT], [PROTAGONIST] must [GOAL].
But [ANTAGONISTIC FORCE] threatens [STAKES].

**Paragraph 2 — Complications (3-5 sentences)**
Expand on the conflict. Show the impossible choice.
Mention the emotional journey. Include the midpoint escalation.
End with the central question/dilemma.

**Paragraph 3 — Bio + Metadata (2-3 sentences)**
[TITLE] is a [WORD COUNT]-word [GENRE] [COMP TITLE] meets [COMP TITLE].
[Relevant bio: writing credits, expertise, own-voices connection].
Thank you for your consideration.

### Comp Title Rules
- Both comps published within last 5 years
- At least one should be a debut or midlist (not Harry Potter)
- "X meets Y" where X = tone/voice and Y = concept/world
- They should make an agent think "I can sell this"

### Synopsis Formula (1-2 pages, single-spaced)
- Present tense, third person
- INCLUDE the ending (agents need to know you can close the story)
- Name only 4-6 characters maximum
- Focus on emotional arc, not subplot details
- Every paragraph should have cause → effect structure

### Back Cover Blurb Formula (150-250 words)
Line 1: Genre-setting hook
Para 1: Character + situation (who they are, what they want)
Para 2: Conflict + stakes (what's in the way, what happens if they fail)
Para 3: Emotional hook / question / twist tease
NEVER reveal the ending in a blurb.
`;

// ─── 7. Beta Feedback Interpretation ─────────────────────────

export const BETA_FEEDBACK_INTERPRETATION = `
## Beta Feedback Interpretation Guide

### The Signal-to-Noise Rule
When 1 beta reader flags something: CONSIDER it.
When 3+ flag the same thing: FIX it.
When all flag it: It's BROKEN.

### Translating Beta Reader Language
- "I was confused" → Unclear cause-and-effect or missing context
- "I got bored here" → Pacing issue — scene doesn't earn its length
- "This felt unrealistic" → Character motivation or world logic gap
- "I didn't like [character]" → Either intentional (good antagonist) or unintentional flaw
- "I saw the twist coming" → Foreshadowing too heavy OR trope too familiar
- "I had to reread this" → Unclear prose, ambiguous pronouns, or complex structure
- "I wanted more of [thing]" → That element is working — give it more space

### What to Ignore
- Preference-based feedback ("I don't like present tense") unless it's your target audience
- "I would have written it differently" — not useful
- Line-level edits from non-editors
- Contradictory feedback that cancels out ("too fast" vs "too slow" from equal-sized groups)

### Prioritization Framework
1. MUST FIX: Confusion, plot holes, character inconsistency (multiple readers)
2. SHOULD FIX: Pacing issues, predictability, emotional disconnects (2-3 readers)
3. CONSIDER: Style preferences, additional scene requests, character likability (1 reader)
4. IGNORE: Personal taste, genre aversion, "I would have done X"
`;

// ─── 8. Revision Strategy ────────────────────────────────────

export const REVISION_STRATEGY = `
## Revision Strategy Guide

### The 4-Pass Revision Method
**Pass 1: STRUCTURAL (Big Picture)**
- Does the story have a clear beginning, middle, and end?
- Does every scene advance plot OR character (ideally both)?
- Are there scenes that can be cut without losing anything?
- Is the pacing right for the genre?
- Do the character arcs complete?
Cut first, add later.

**Pass 2: SCENE-LEVEL**
- Does each scene have a goal, conflict, and outcome?
- Are transitions smooth?
- Is the POV consistent within each scene?
- Do chapter endings hook the reader?
- Are there scenes that START too early or END too late?

**Pass 3: LINE-LEVEL (Prose)**
- Cut every word that doesn't earn its place
- Replace weak verbs with strong ones
- Eliminate filter words (saw, heard, felt, noticed)
- Vary sentence length deliberately
- Check for AI tells and clichés
- Read dialogue aloud — does it sound natural?

**Pass 4: POLISH**
- Typos, grammar, punctuation
- Formatting consistency
- Name/place/detail consistency
- Fact-checking
- Read the entire manuscript aloud (or use TTS)

### Kill Your Darlings Protocol
If you're attached to a passage but it doesn't serve the story:
1. Copy it to a "Cuts" document (never truly delete)
2. Remove it from the manuscript
3. Read the surrounding text — is anything lost?
4. If yes, find a way to integrate the essential part differently
5. If no, it was self-indulgent. Let it go.
`;

// ─── 9. Series Bible Management ──────────────────────────────

export const SERIES_BIBLE_MANAGEMENT = `
## Series Bible Management Guide

### What a Series Bible Must Track
**Characters**: Full profiles, relationships, arcs across books, age progression
**Timeline**: Master chronology across all books, time gaps between books
**World Rules**: Magic systems, technology, social structures — and ANY exceptions
**Plot Threads**: Which threads are open, which are resolved, which span multiple books
**Promises**: Things set up in earlier books that MUST pay off later (Chekhov's arsenal)
**Changes**: What changed between books — political shifts, deaths, relationships
**Retcons**: Anything intentionally changed from earlier books (document it!)

### Series Continuity Checklist (per new book)
- [ ] Character ages updated correctly
- [ ] Injuries/scars/changes from previous book persist
- [ ] Relationships reflect end-of-previous-book status
- [ ] World state reflects consequences of previous book's events
- [ ] No resurrected items/characters without explanation
- [ ] Consistent naming (places, people, objects)
- [ ] Timeline arithmetic works (ages, distances, travel times)

### Cross-Book Reference System
For each significant entity, track:
- First appearance (book + chapter)
- Last known state
- Planned future role
- Dependencies (who/what relies on this entity)
`;

// ─── 10. Self-Editing Checklist ──────────────────────────────

export const SELF_EDITING_CHECKLIST = `
## Self-Editing Checklist

### Before Submitting to ANY Editor/Agent
- [ ] Spell-checked with TWO tools (not just one)
- [ ] Read the opening 3 pages aloud — do they HOOK?
- [ ] Every chapter ending has a reason to turn the page
- [ ] No characters appear without introduction
- [ ] No plot points appear without setup
- [ ] The ending resolves the central question posed in Act 1
- [ ] The theme is expressed through story events, not stated directly
- [ ] No excessive use of: adverbs, passive voice, filter words
- [ ] Dialogue tags are invisible (mostly "said")
- [ ] Each scene has been justified: "Why does this scene exist?"

### The "Fresh Eyes" Technique
After finishing your revision, wait at least 48 hours before the final read.
Read in a different format (print if you wrote on screen, Kindle if you wrote in Word).
Read in a different location than where you wrote.
These changes help you see the text as a reader, not as the writer.

### Numbers to Track
- Total word count (is it in genre range?)
- Average chapter length (consistent or intentionally varied?)
- Dialogue-to-narrative ratio (40-60% dialogue is typical for fiction)
- "Was/were" frequency (indicator of passive voice)
- Adverb count per chapter (decreasing is good)
- Unique words used (type-token ratio — higher = richer vocabulary)
`;

